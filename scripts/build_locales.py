LOCALES = {
    "ta": TA, "te": TE, "kn": KN, "ml": ML,
    "mr": MR, "bn": BN, "gu": GU, "pa": PA,
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check", action="store_true",
        help="verify EN parity per locale without writing",
    )
    args = ap.parse_args()

    en_path = LOC / "en.json"
    en = json.loads(en_path.read_text(encoding="utf-8"))
    en_keys = set(en.keys())

    failed = False
    for code, data in LOCALES.items():
        missing = [k for k in en_keys if k not in data]
        extra = [k for k in data if k not in en_keys]
        pct = round(100 * (len(en_keys) - len(missing)) / len(en_keys), 1)
        path = LOC / f"{code}.json"
        verb = "would-write" if args.check else "wrote"
        if not args.check:
            path.write_text(
                json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True)
                + "\n",
                encoding="utf-8",
            )
        print(
            f"  {code:>3}  {verb}  keys={len(data)}  "
            f"coverage={pct}%  missing={len(missing)}  extra={len(extra)}",
        )
        if missing and pct < 90.0:
            print(f"      MISSING (sample): {missing[:5]}", file=sys.stderr)
            failed = True
        if extra:
            print(f"      EXTRA (not in EN): {extra[:5]}", file=sys.stderr)
            failed = True

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
